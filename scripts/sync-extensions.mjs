import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const configPath = path.join(root, "spenta.extensions.json");
const outputPath = path.join(root, "src/extensions/generated-registry.ts");
const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
const modules = Array.isArray(config.extensions) ? [...new Set(config.extensions.filter(value => typeof value === "string" && value.trim()))] : [];
const imports = modules.map((specifier, index) => `import extension${index} from ${JSON.stringify(specifier)};`).join("\n");
const values = modules.map((_, index) => `extension${index}`).join(", ");
const output = `/* AUTO-GENERATED by scripts/sync-extensions.mjs. Do not edit manually. */\nimport type { ExtensionDefinition } from "./sdk";\n${imports}${imports ? "\n" : ""}\nexport const generatedExtensions: ExtensionDefinition[] = [${values}];\n`;
fs.writeFileSync(outputPath, output);
console.log(`Synced ${modules.length} external code extension${modules.length === 1 ? "" : "s"}.`);
